// Read titles from existing guide front matter so a stale tracking file cannot
// cause an already-published title to be generated again.
function loadExistingGuideTitles() {
  if (!fs.existsSync(GUIDES_DIR)) return [];

  return fs.readdirSync(GUIDES_DIR)
    .filter(file => file.endsWith('.md'))
    .map(file => fs.readFileSync(path.join(GUIDES_DIR, file), 'utf-8'))
    .map(content => content.match(/^title:\s*["']?(.+?)["']?\s*$/m)?.[1])
    .filter(Boolean);
}

// Helper: Convert title to slug format for comparison
function titleToSlug(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

// Select a random category first, then a random unused topic in that category.
// Avoid the category used most recently when another category is available.
function selectNextTopic(topics, usedTitles, generatedTopics) {
  const unusedTopics = topics.filter(
    topic => !usedTitles.has(topic.title)
  );

  if (unusedTopics.length === 0) {
    return null;
  }

  const availableCategories = [...new Set(unusedTopics.map(topic => topic.category))];
  const lastGeneratedTitle = generatedTopics[generatedTopics.length - 1];
  const lastGeneratedCategory = topics.find(
    topic => topic.title === lastGeneratedTitle
  )?.category;
  const eligibleCategories = availableCategories.length > 1
    ? availableCategories.filter(category => category !== lastGeneratedCategory)
    : availableCategories;
  const selectedCategory = eligibleCategories[
    Math.floor(Math.random() * eligibleCategories.length)
  ];
  const categoryTopics = unusedTopics.filter(
    topic => topic.category === selectedCategory
  );
  const selected = categoryTopics[Math.floor(Math.random() * categoryTopics.length)];
  console.log(`📄 Generating ${selected.category}: ${selected.organization}`);
  return selected;
}

// Validate a URL by checking if it returns a successful response
async function validateUrl(url, timeout = 10000) {
  try {
    const response = await axios.head(url, {
      timeout,
      maxRedirects: 5,
      validateStatus: (status) => status >= 200 && status < 400
    });
    return true;
  } catch (error) {
    // Try GET if HEAD fails (some servers don't support HEAD)
    try {
      const response = await axios.get(url, {
        timeout,
        maxRedirects: 5,
        validateStatus: (status) => status >= 200 && status < 400,
        responseType: 'stream'
      });
      // Cancel the stream immediately, we just need to check if it's accessible
      response.data.destroy();
      return true;
    } catch (getError) {
      console.log(`  ✗ Invalid URL: ${url} (${getError.message})`);
      return false;
    }
  }
}

// Fetch the required official source and convert it to bounded plain text for the model.
async function fetchSourceContent(url, timeout = 30000) {
  const response = await axios.get(url, {
    timeout,
    maxRedirects: 5,
    headers: {
      'User-Agent': 'decent.charity article generator'
    },
    validateStatus: status => status >= 200 && status < 400
  });

  const html = String(response.data);
  const plainText = html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\s+/g, ' ')
    .trim();

  if (plainText.length < 200) {
    throw new Error(`Primary source did not return enough usable content: ${url}`);
  }

  return plainText.slice(0, 16000);
}

// Extract and validate URLs from markdown content
async function validateLinksInContent(content) {
  // Match markdown links: [text](url)
  const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  const matches = [...content.matchAll(linkRegex)];

  if (matches.length === 0) {
    return content;
  }

  console.log(`Validating ${matches.length} links...`);

  const validatedLinks = await Promise.all(
    matches.map(async (match) => {
      const fullMatch = match[0];
      const text = match[1];
      const url = match[2];

      // Skip internal links (starting with /)
      if (url.startsWith('/') || url.startsWith('#')) {
        return { fullMatch, isValid: true };
      }

      const isValid = await validateUrl(url);
      if (isValid) {
        console.log(`  ✓ Valid: ${url}`);
      }

      return { fullMatch, isValid };
    })
  );

  // Remove invalid links from content
  let validatedContent = content;
  validatedLinks.forEach(({ fullMatch, isValid }) => {
    if (!isValid) {
      // Remove the entire line containing the invalid link
      const lines = validatedContent.split('\n');
      validatedContent = lines
        .filter(line => !line.includes(fullMatch))
        .join('\n');
    }
  });

  const removedCount = validatedLinks.filter(l => !l.isValid).length;
  if (removedCount > 0) {
    console.log(`Removed ${removedCount} invalid link(s)`);
  }

  return validatedContent;
}

// Helper function to detect transient errors that should be retried
function isTransientError(error) {
  // Check for HTTP status codes indicating transient issues
  if (error.response) {
    const status = error.response.status;
    if (status === 502 || status === 503 || status === 504) {
      return true;
    }
  }

  // Check for network errors
  if (error.code) {
    const transientCodes = ['ECONNRESET', 'ETIMEDOUT', 'ECONNREFUSED', 'ENETUNREACH', 'ECONNABORTED', 'EAI_AGAIN', 'ENOTFOUND', 'ESOCKETTIMEDOUT'];
    if (transientCodes.includes(error.code)) {
      return true;
    }
  }

  if (error.message && /timeout|socket hang up|network/i.test(error.message)) {
    return true;
  }

  return false;
}

