// Generate article image prompt from topic
function generateImagePrompt(title, organization, category) {
  return {
    prompt: `Editorial city street photo about community support in the ${category.replace(/-/g, ' ')} category. Documentary urban streetscape, natural light, candid realism, respectful hopeful mood. Rich black and white with exactly one prominent element in one primary color: red, blue, or yellow. ZERO TEXT OR TEXT-LIKE MARKS: no title, organization name, letters, words, numbers, captions, logos, branding, storefront lettering, signs, posters, ads, labels, packaging text, license plates, watermarks, or signatures, including blurred, partial, invented, or illegible writing. Avoid surfaces that normally display writing.`,
    negative_prompt: `text, letters, words, numbers, captions, typography, logos, branding, storefront lettering, signs, posters, advertisements, labels, packaging text, license plates, watermark, signature, glyphs, symbols, multiple colored elements, full color, sepia, exploitative imagery, staged hardship, identifiable vulnerable people`
  };
}

// Helper function to try generating image with a specific FLUX model
async function tryGenerateWithModel(promptData, modelUrl, modelName, steps, maxRetries = 3, timeoutMs = 300000) {
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      console.log(`Attempt ${attempt}/${maxRetries}: Sending prompt to ${modelName}...`);

      const requestBody = {
        prompt: promptData.prompt,
        width: 1024,
        height: 1024,
        seed: Math.floor(Math.random() * 1000000),
        steps: steps
      };

      // Note: Negative prompt may not be supported by NVIDIA FLUX API
      // Commenting out for now to avoid 422 errors
      // if (promptData.negative_prompt && modelName.includes('dev')) {
      //   requestBody.negative_prompt = promptData.negative_prompt;
      // }

      const response = await axios.post(
        modelUrl,
        requestBody,
        {
          headers: {
            'Authorization': `Bearer ${process.env.NVIDIA_API_KEY}`,
            'Content-Type': 'application/json',
            'Accept': 'application/json'
          },
          timeout: timeoutMs
        }
      );

      if (!response.data || !response.data.artifacts || response.data.artifacts.length === 0) {
        throw new Error('No image data in response');
      }

      const artifact = response.data.artifacts[0];
      if (artifact.finishReason !== 'SUCCESS') {
        throw new Error(`Image generation failed: ${artifact.finishReason}`);
      }

      return artifact.base64;

    } catch (error) {
      console.error(`✗ Attempt ${attempt} failed:`, error.message);
      if (error.response) {
        console.error('API Response:', JSON.stringify(error.response.data) || error.response.status);
      }

      if (attempt < maxRetries) {
        const waitTime = Math.pow(2, attempt) * 10000; // 20s, 40s, 80s
        console.log(`Waiting ${waitTime/1000}s before retry...`);
        await new Promise(resolve => setTimeout(resolve, waitTime));
      }
    }
  }

  return null;
}

// Generate and save image using NVIDIA's FLUX models with fallback
async function generateAndSaveImage(title, organization, category) {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  const filename = `${slug}.jpg`;
  const filepath = path.join(IMAGES_DIR, filename);

  console.log(`Generating article image for: ${title}`);

  const prompt = generateImagePrompt(title, organization, category);
  let imageBase64 = null;
  let modelUsed = null;

  for (const model of IMAGE_MODELS) {
    console.log(`\n🎨 Trying ${model.name}...`);
    imageBase64 = await tryGenerateWithModel(
      prompt,
      model.url,
      model.name,
      model.steps,
      model.retries,
      model.timeoutMs
    );

    if (imageBase64) {
      modelUsed = model.key;
      break;
    }

    console.log(`\n🔄 ${model.name} failed; trying next available image model...`);
  }

  // If both models failed
  if (!imageBase64) {
    console.error('⚠️  All attempts with both FLUX models failed.');
    return null;
  }

  // Save the image
  const imageBuffer = Buffer.from(imageBase64, 'base64');
  fs.writeFileSync(filepath, imageBuffer);

  const creditInfo = IMAGE_MODELS.find(model => model.key === modelUsed);

  console.log(`✓ AI-generated image saved: ${filename} (using ${modelUsed})`);

  return {
    path: `/assets/images/guides/${filename}`,
    ...creditInfo
  };
}

// Update guide front matter with image data
function updateGuideFrontMatter(filepath, imageData) {
  const content = fs.readFileSync(filepath, 'utf-8');
  const frontMatterMatch = content.match(/^---\n([\s\S]*?)\n---/);

  if (!frontMatterMatch) {
    console.error('Could not find front matter');
    return false;
  }

  const oldFrontMatter = frontMatterMatch[0];
  let frontMatterContent = frontMatterMatch[1];

  // Check if image fields already exist
  if (frontMatterContent.includes('image:')) {
    console.log('Front matter already has image field, skipping update');
    return false;
  }

  // Add image fields
  const imageFields = `image: "${imageData.path}"
image_credit: "${imageData.credit}"
image_credit_url: "${imageData.credit_url}"`;

  const newFrontMatter = `---\n${frontMatterContent}\n${imageFields}\n---`;
  const newContent = content.replace(oldFrontMatter, newFrontMatter);

  fs.writeFileSync(filepath, newContent);
  console.log('Front matter updated successfully');
  return true;
}

async function main() {
  if (!process.env.NVIDIA_API_KEY) {
    console.error('NVIDIA_API_KEY environment variable is not set');
    process.exit(1);
  }

  const guideFile = process.argv[2];

  if (!guideFile) {
    console.error('Usage: node scripts/add-missing-image.js <guide-file.md>');
    process.exit(1);
  }

  const guidePath = path.join(GUIDES_DIR, guideFile);

  if (!fs.existsSync(guidePath)) {
    console.error(`Guide not found: ${guideFile}`);
    process.exit(1);
  }

  console.log(`Adding image to: ${guideFile}\n`);

  // Parse front matter to get title and tags
  const content = fs.readFileSync(guidePath, 'utf-8');
  const frontMatterMatch = content.match(/^---\n([\s\S]*?)\n---/);

  if (!frontMatterMatch) {
    console.error('Could not parse front matter');
    process.exit(1);
  }

  const frontMatter = frontMatterMatch[1];
  const titleMatch = frontMatter.match(/title:\s*"(.+?)"/);
  const organizationMatch = frontMatter.match(/organization:\s*"(.+?)"/);
  const categoryMatch = frontMatter.match(/category:\s*(.+)/);

  if (!titleMatch || !organizationMatch || !categoryMatch) {
    console.error('Could not find title, organization, or category');
    process.exit(1);
  }

  const title = titleMatch[1];
  const organization = organizationMatch[1];
  const category = categoryMatch[1].trim().replace(/^["']|["']$/g, '');

  console.log(`Title: ${title}`);
  console.log(`Organization: ${organization}`);
  console.log(`Category: ${category}\n`);

  // Generate image
  const imageData = await generateAndSaveImage(title, organization, category);

  if (!imageData) {
    console.error('Failed to generate image');
    process.exit(1);
  }

  // Update front matter
  const updated = updateGuideFrontMatter(guidePath, imageData);

  if (updated) {
    console.log('\n✨ Done! Image added successfully.');
  } else {
    console.log('\n⚠️  Front matter not updated');
  }
}

if (require.main === module) {
  main().catch(error => {
    console.error(error.message);
    process.exit(1);
  });
}
